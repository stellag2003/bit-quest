const cache = new Map();

export function iconMaskUrl(name) {
  if (cache.has(name)) return cache.get(name);
  const rows = ICON_BITMAPS[name];
  if (!rows) throw new Error(`Ícone desconhecido: ${name}`);
  const width = Math.max(...rows.map((r) => r.length));
  const size = Math.max(width, rows.length);
  const ox = Math.floor((size - width) / 2);
  const oy = Math.floor((size - rows.length) / 2);
  let path = '';
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch === '#') path += `M${x + ox} ${y + oy}h1v1h-1z`;
  }));
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${size} ${size}' shape-rendering='crispEdges'><path d='${path}'/></svg>`;
  const url = `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
  cache.set(name, url);
  return url;
}

export function icon(name, className = '') {
  const el = document.createElement('span');
  el.className = `ico ${className}`.trim();
  el.setAttribute('aria-hidden', 'true');
  el.style.setProperty('--icon', iconMaskUrl(name));
  return el;
}
